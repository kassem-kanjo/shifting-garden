"""Pack the chosen scenes into web/scenes.js as data URIs.

Data URIs keep the canvas untainted, so the glitch effects can read pixels even when the
page is opened from a file (in a browser or inside the screensaver).

usage: python3 tools/pack_scenes.py
"""
import base64, io, json, pathlib
import cv2
import numpy as np
from PIL import Image, ImageEnhance

ROOT = pathlib.Path(__file__).resolve().parent.parent
SCENES = [  # order they play in; source file in sources/ (raw Midjourney picks, not in git)
    ("Flowers and swallows", "flowers and swallows.webp"),
    ("Koi and lotus", "koi and lotus.png"),
    ("Cranes and pine", "cranes and pine.png"),
    ("Peonies and butterflies", "peonies and butterflies.webp"),
]
WIDTH, QUALITY = 2560, 84
PAPER = np.array([246, 237, 214], float)   # the clean cream the reference prints on


def clean(im):
    """Midjourney prints look aged. Pull the paper to clean cream and lift the colour."""
    a = np.asarray(im, float)
    lum = a.mean(axis=2)
    paper = np.percentile(a[lum > np.percentile(lum, 70)], 60, axis=0)   # typical paper colour
    a = np.clip(a * (PAPER / paper), 0, 255)
    im = Image.fromarray(a.astype("uint8"))
    im = ImageEnhance.Color(im).enhance(1.28)
    im = ImageEnhance.Contrast(im).enhance(1.08)
    return im


def screenprint(im, inks=14):
    """Flatten a scene into a screenprint: smooth away the wood grain, posterise to a small
    set of inks, snap the paper ink to one clean cream, and put crisp black keylines back."""
    a = cv2.cvtColor(np.asarray(im), cv2.COLOR_RGB2BGR)
    sm = cv2.pyrMeanShiftFiltering(a, 10, 22)
    sm = cv2.bilateralFilter(sm, 9, 40, 9)
    z = sm.reshape(-1, 3).astype(np.float32)
    crit = (cv2.TERM_CRITERIA_EPS + cv2.TERM_CRITERIA_MAX_ITER, 20, 1.0)
    cv2.setRNGSeed(7)
    _, lab, cen = cv2.kmeans(z, inks, None, crit, 2, cv2.KMEANS_PP_CENTERS)
    paper_bgr = PAPER[::-1]
    nearest = int(np.argmin(((cen - paper_bgr) ** 2).sum(1)))
    cen[nearest] = paper_bgr                                    # one flat paper colour
    flat = cen.astype(np.uint8)[lab.flatten()].reshape(sm.shape)

    # keylines: dark, thin structures from the original, minus speckle
    grey = cv2.cvtColor(a, cv2.COLOR_BGR2GRAY)
    line = cv2.adaptiveThreshold(grey, 255, cv2.ADAPTIVE_THRESH_MEAN_C, cv2.THRESH_BINARY_INV, 17, 14)
    n, lbl, stats, _ = cv2.connectedComponentsWithStats(line, 8)
    keep = np.zeros(n, bool); keep[1:] = stats[1:, cv2.CC_STAT_AREA] >= 40
    line = keep[lbl]
    out = flat.astype(float)
    out[line] = out[line] * 0.18 + np.array([26, 26, 26]) * 0.82   # sumi ink over the colour
    return Image.fromarray(cv2.cvtColor(out.astype(np.uint8), cv2.COLOR_BGR2RGB))

out, total = [], 0
for name, file in SCENES:
    path = ROOT / "sources" / file
    if not path.exists():
        print(f"skip {name}: {file} not found")
        continue
    im = clean(Image.open(path).convert("RGB"))
    im = im.resize((WIDTH, round(im.height * WIDTH / im.width)), Image.LANCZOS)
    im = screenprint(im)
    buf = io.BytesIO(); im.save(buf, "JPEG", quality=QUALITY, optimize=True, progressive=True)
    total += buf.tell()
    out.append({"name": name, "src": "data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode()})
    print(f"{name}: {im.size[0]}x{im.size[1]}, {buf.tell() // 1024} KB")

js = "// Generated by tools/pack_scenes.py. Do not edit.\nwindow.SHIFTING_GARDEN_SCENES = " + json.dumps(out) + ";\n"
(ROOT / "web" / "scenes.js").write_text(js)
print(f"{len(out)} scenes, {total // 1024} KB of JPEG → web/scenes.js")
